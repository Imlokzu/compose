#!/usr/bin/env python3
"""Generate Android vectors from Compose's canonical desktop SVG icons."""
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
ANDROID = "http://schemas.android.com/apk/res/android"
ET.register_namespace("android", ANDROID)


def geometry(element):
    a = element.attrib
    tag = element.tag.rsplit("}", 1)[-1]
    if tag == "path":
        return a["d"]
    if tag in ("circle", "ellipse"):
        x, y = float(a["cx"]), float(a["cy"])
        rx, ry = float(a.get("rx", a.get("r", 0))), float(a.get("ry", a.get("r", 0)))
        return f"M{x-rx},{y}a{rx},{ry} 0 1,0 {2*rx},0a{rx},{ry} 0 1,0 {-2*rx},0Z"
    if tag == "rect":
        x, y, w, h = (float(a[k]) for k in ("x", "y", "width", "height"))
        r = min(float(a.get("rx", 0)), w / 2, h / 2)
        return (f"M{x+r},{y}h{w-2*r}a{r},{r} 0 0,1 {r},{r}v{h-2*r}"
                f"a{r},{r} 0 0,1 {-r},{r}h{-w+2*r}a{r},{r} 0 0,1 {-r},{-r}"
                f"v{-h+2*r}a{r},{r} 0 0,1 {r},{-r}Z") if r else f"M{x},{y}h{w}v{h}h{-w}Z"
    raise ValueError(f"Unsupported SVG primitive: {tag}")


def color(value):
    if value in ("white", "black"):
        return "#FFFFFF" if value == "white" else "#000000"
    if value == "currentColor":
        return "#000000"
    if value == "none":
        return "#00000000"
    if value.startswith("#") and len(value) == 4:
        return "#" + "".join(c * 2 for c in value[1:])
    return value


def generate():
    output = ROOT / "android/app/src/main/res/drawable"
    output.mkdir(parents=True, exist_ok=True)
    for file in sorted((ROOT / "assets/icons").glob("*.svg")):
        svg = ET.parse(file).getroot()
        _, _, w, h = svg.attrib["viewBox"].split()
        vector = ET.Element("vector", {f"{{{ANDROID}}}{k}": v for k, v in {
            "width": f"{w}dp", "height": f"{h}dp", "viewportWidth": w, "viewportHeight": h}.items()})
        for element in svg:
            attrs = svg.attrib | element.attrib
            path = {"pathData": geometry(element), "fillColor": color(attrs.get("fill", "#000"))}
            if attrs.get("stroke", "none") != "none":
                path.update(strokeColor=color(attrs["stroke"]), strokeWidth=attrs.get("stroke-width", "1"),
                            strokeLineCap=attrs.get("stroke-linecap", "butt"), strokeLineJoin=attrs.get("stroke-linejoin", "miter"))
            ET.SubElement(vector, "path", {f"{{{ANDROID}}}{k}": v for k, v in path.items()})
        ET.indent(vector, space="    ")
        (output / f"ic_{file.stem.replace('-', '_')}.xml").write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/android-icons.py from assets/icons. -->\n'
            + ET.tostring(vector, encoding="unicode") + "\n")


if __name__ == "__main__":
    generate()
